// Bundles MapLibre + our neon style + map engine into one self-contained HTML string
// that the app loads in a WebView (works offline except for map tiles).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const mlDir = path.dirname(require.resolve('maplibre-gl/package.json'));
const js = fs.readFileSync(path.join(mlDir, 'dist/maplibre-gl.js'), 'utf8');
const css = fs.readFileSync(path.join(mlDir, 'dist/maplibre-gl.css'), 'utf8');
const style = fs.readFileSync(path.join(root, 'src/map/web/style.js'), 'utf8');
const engine = fs.readFileSync(path.join(root, 'src/map/web/map.js'), 'utf8');
// Pre-extracted towers for the far-zoom 3D skyline (see scripts/build-skyline.mjs).
const skyline = fs.readFileSync(path.join(root, 'src/map/web/skyline.json'), 'utf8');
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<style>${css}
html,body,#map{margin:0;padding:0;width:100%;height:100%;background:#14111C;overflow:hidden;-webkit-user-select:none;user-select:none;-webkit-tap-highlight-color:transparent}
#fx{position:absolute;inset:0;pointer-events:none;z-index:2;
background:radial-gradient(ellipse at 50% 45%,rgba(0,0,0,0) 60%,rgba(10,8,16,.45) 100%)}
.maplibregl-ctrl-attrib{background:rgba(11,6,24,.6)!important;color:#8D7FC0!important;font:10px sans-serif}
.maplibregl-ctrl-attrib a{color:#B89AF0!important}
.maplibregl-ctrl-attrib-button{filter:invert(1)}
.maplibregl-ctrl-bottom-right{bottom:auto;top:calc(env(safe-area-inset-top) + 116px);right:2px}
.maplibregl-ctrl-attrib{opacity:.7}
.pulse{width:18px;height:18px;border-radius:50%;pointer-events:none;background:var(--c);opacity:.0;animation:pulse 1.8s ease-out infinite;will-change:transform,opacity}
@keyframes pulse{0%{transform:scale(1);opacity:.55}100%{transform:scale(4.2);opacity:0}}
.me{width:22px;height:22px;position:relative;pointer-events:none}
.me-dot{position:absolute;inset:3px;border-radius:50%;background:#fff;border:3px solid #08060C;box-sizing:border-box;box-shadow:0 0 0 2px rgba(255,255,255,.35)}
.me-ring{position:absolute;inset:0;border-radius:50%;background:#fff;animation:pulse 2s ease-out infinite;will-change:transform,opacity}
.me-cone{display:none;position:absolute;left:50%;top:50%;width:0;height:0;margin-left:-14px;margin-top:-40px;border-left:14px solid transparent;border-right:14px solid transparent;border-bottom:34px solid rgba(255,255,255,.28)}
.me.has-heading .me-cone{display:block}
body.drive .me-dot{background:#fff;border-color:#C64BFF;inset:1px;border-width:4px}
body.drive #fx{background:radial-gradient(ellipse at 50% 70%,rgba(0,0,0,0) 45%,rgba(10,8,16,.6) 100%)}
</style></head><body><div id="map"></div><div id="fx"></div>
<script>${js}</script><script>window.__SKYLINE=${skyline};</script><script>${style}</script><script>${engine}</script></body></html>`;
const out = `// AUTO-GENERATED by scripts/build-map-html.mjs — do not edit.\n// eslint-disable-next-line\nexport const MAP_HTML: string = ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(root, 'src/map/mapHtml.generated.ts'), out);
fs.writeFileSync(path.join(root, 'src/map/web/preview.html'), html);
console.log('map html built:', (html.length / 1024).toFixed(0), 'KB');
